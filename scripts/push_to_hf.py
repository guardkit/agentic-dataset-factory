def _hf_api():
    from huggingface_hub import HfApi

    api = HfApi()
    try:
        info = api.whoami()
    except Exception as e:
        raise SystemExit(
            "Hugging Face auth not configured. Run `hf auth login` (or set "
            f"HF_TOKEN) with a *write* token. Underlying error: {e}"
        )
    return api, info


def cmd_whoami(_args: argparse.Namespace) -> int:
    _, info = _hf_api()
    print(json.dumps({"name": info.get("name"), "type": info.get("type"), "orgs": [o.get("name") for o in info.get("orgs", [])]}, indent=2))
    return 0


def cmd_render_card(args: argparse.Namespace) -> int:
    spec = DomainSpec.load(args.domain)
    runbook_suffix = "architect" if args.domain == "architect-agent" else args.domain.split("-")[0]
    content = _CARD_TEMPLATE.format(
        display_name=spec.display_name,
        one_liner=spec.one_liner,
        intended_use=spec.intended_use,
        limitations=spec.limitations,
        training_data_summary=spec.training_data_summary,
        sample_prompt=spec.sample_prompt,
        domain_tag=spec.slug,
        domain_slug=spec.slug,
        runbook_suffix=runbook_suffix,
        repo_id=args.repo_id,
    )
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(content)
    print(f"wrote {out} ({len(content)} bytes)")
    return 0


def cmd_create_repo(args: argparse.Namespace) -> int:
    api, _ = _hf_api()
    if args.dry_run:
        print(f"DRY-RUN: would create model repo {args.repo_id} (private={args.private})")
        return 0
    url = api.create_repo(
        repo_id=args.repo_id,
        repo_type="model",
        private=args.private,
        exist_ok=True,
    )
    print(f"repo ready: {url}")
    return 0


def cmd_push(args: argparse.Namespace) -> int:
    api, _ = _hf_api()
    src = Path(args.src).expanduser().resolve()
    if not src.exists():
        raise SystemExit(f"source path does not exist: {src}")

    allow = list(args.include) if args.include else None
    ignore = list(args.exclude) if args.exclude else None

    if src.is_file():
        if args.dry_run:
            print(f"DRY-RUN: would upload file {src} -> {args.repo_id}:{args.path_in_repo or src.name}")
            return 0
        api.upload_file(
            path_or_fileobj=str(src),
            path_in_repo=args.path_in_repo or src.name,
            repo_id=args.repo_id,
            repo_type="model",
            commit_message=args.message,
        )
    else:
        if args.dry_run:
            print(f"DRY-RUN: would upload folder {src} -> {args.repo_id} (allow={allow}, ignore={ignore}, path_in_repo={args.path_in_repo or '/'})")
            return 0
        api.upload_folder(
            folder_path=str(src),
            path_in_repo=args.path_in_repo or "",
            repo_id=args.repo_id,
            repo_type="model",
            commit_message=args.message,
            allow_patterns=allow,
            ignore_patterns=ignore,
        )
    print(f"uploaded {src} -> https://huggingface.co/{args.repo_id}")
    return 0


def cmd_verify(args: argparse.Namespace) -> int:
    api, _ = _hf_api()
    files = list(api.list_repo_files(repo_id=args.repo_id, repo_type="model"))
    print(f"{args.repo_id}: {len(files)} files")
    for f in sorted(files):
        print(f"  {f}")

    if args.require:
        missing = [pat for pat in args.require if not any(_match(f, pat) for f in files)]
        if missing:
            print(f"MISSING expected files: {missing}", file=sys.stderr)
            return 1
        print("all required files present")
    return 0


def _match(filename: str, pattern: str) -> bool:
    if "*" in pattern:
        import fnmatch
        return fnmatch.fnmatch(filename, pattern)
    return filename == pattern or filename.endswith("/" + pattern)


def _build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)

    sub.add_parser("whoami").set_defaults(func=cmd_whoami)

    rc = sub.add_parser("render-card", help="Generate a model-card README.md")
    rc.add_argument("--domain", required=True, choices=sorted(_DOMAINS))
    rc.add_argument("--repo-id", required=True, help="owner/name on HF (used inside the card)")
    rc.add_argument("--out", required=True, help="path to write the card to")
    rc.set_defaults(func=cmd_render_card)

    cr = sub.add_parser("create-repo", help="Create a model repo on the Hub (idempotent)")
    cr.add_argument("--repo-id", required=True)
    cr.add_argument("--private", action="store_true")
    cr.add_argument("--dry-run", action="store_true")
    cr.set_defaults(func=cmd_create_repo)

    pu = sub.add_parser("push", help="Upload a directory or single file to a repo")
    pu.add_argument("--repo-id", required=True)
    pu.add_argument("--src", required=True)
    pu.add_argument("--path-in-repo", default=None, help="Destination subpath inside the repo")
    pu.add_argument("--include", nargs="*", help="Allow-list glob patterns (passed to upload_folder)")
    pu.add_argument("--exclude", nargs="*", help="Ignore glob patterns")
    pu.add_argument("--message", default="upload artefacts via push_to_hf.py")
    pu.add_argument("--dry-run", action="store_true")
    pu.set_defaults(func=cmd_push)

    ve = sub.add_parser("verify", help="List remote files; optionally assert required ones are present")
    ve.add_argument("--repo-id", required=True)
    ve.add_argument("--require", nargs="*", help="Filenames or globs that must be in the repo")
    ve.set_defaults(func=cmd_verify)

    return p


def main(argv: Iterable[str] | None = None) -> int:
    args = _build_parser().parse_args(list(argv) if argv is not None else None)
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
