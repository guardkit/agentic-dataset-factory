"""Helper for uploading fine-tuned Gemma-4 MoE artefacts to Hugging Face.

Designed to be driven from RUNBOOK-huggingface-upload.md. Each subcommand maps
to one phase of that runbook so a failure stops the phase cleanly and can be
retried in isolation.

Subcommands
-----------
whoami          : Confirm the active HF token and print the resolved username.
render-card     : Write a domain-aware README.md / model-card file.
create-repo     : Create a model repo on the Hub (idempotent; --exist-ok).
push            : Upload a directory (or single file) to a repo with hf_transfer.
verify          : List remote files and confirm the expected artefacts are present.

The script never deletes remote files. It uses upload_folder with `delete_patterns`
disabled so repeated runs are additive.
"""

